export function authDevLog(event: AuthEvent, httpStatus?: number): void {
  if (!__DEV__) return;
  if (httpStatus === undefined) console.info('[Auth DEV]', event);
  else console.info('[Auth DEV]', event, `HTTP ${httpStatus}`);
}
